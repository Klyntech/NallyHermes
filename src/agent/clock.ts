import { eq } from "drizzle-orm";
import { config } from "../config.js";
import { db } from "../db/client.js";
import { users } from "../db/schema.js";

export function isValidTimezone(timezone: string): boolean {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: timezone });
    return true;
  } catch {
    return false;
  }
}

export async function getUserTimezone(telegramId: string): Promise<string> {
  const [user] = await db.select({ timezone: users.timezone })
    .from(users).where(eq(users.telegramId, telegramId)).limit(1);
  const timezone = user?.timezone || config.DEFAULT_TIMEZONE;
  return isValidTimezone(timezone) ? timezone : "Africa/Lagos";
}

export async function setUserTimezone(telegramId: string, timezone: string): Promise<void> {
  if (!isValidTimezone(timezone)) throw new Error("Use a valid IANA timezone, for example Africa/Lagos or Europe/London.");
  const updated = await db.update(users).set({ timezone }).where(eq(users.telegramId, telegramId)).returning({ id: users.id });
  if (!updated.length) throw new Error("Your Telegram profile is not ready. Send /start and try again.");
}

export function formatDateTimeInTimezone(date: Date, timezone: string): string {
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: timezone,
    dateStyle: "full",
    timeStyle: "short"
  }).format(date);
}

/** Snapshot the server clock and render it in the Telegram user's saved timezone. */
export async function buildClockContext(telegramId: string, now = new Date()): Promise<string> {
  const timezone = await getUserTimezone(telegramId);
  const local = new Intl.DateTimeFormat("en-CA", {
    timeZone: timezone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    weekday: "long",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23"
  }).formatToParts(now);
  const value = (type: string) => local.find((part) => part.type === type)?.value ?? "";
  const offset = new Intl.DateTimeFormat("en-US", {
    timeZone: timezone,
    timeZoneName: "longOffset",
    hour: "2-digit",
    minute: "2-digit"
  }).formatToParts(now).find((part) => part.type === "timeZoneName")?.value ?? "unknown";

  return [
    "TRUSTED CURRENT TIME CONTEXT (generated by the application; authoritative for this request):",
    `UTC instant: ${now.toISOString()}`,
    `User timezone: ${timezone}`,
    `User local date: ${value("year")}-${value("month")}-${value("day")} (${value("weekday")})`,
    `User local time: ${value("hour")}:${value("minute")}:${value("second")}`,
    `Current UTC offset: ${offset}`,
    "Use this snapshot to interpret relative dates and times. Do not infer the current date from training data, website publication dates, or conversation history."
  ].join("\n");
}
